// Formal report page, in jsdom. Run from the repo root: node frontend/tests/report_test.js
const fs = require("fs");
const path = require("path");
const { JSDOM } = require("jsdom");
const root = path.join(__dirname, "..");
const html = fs.readFileSync(path.join(root, "report.html"), "utf8");
const fixtures = fs.readFileSync(path.join(root, "data/demo_fixtures.js"), "utf8");
const script = fs.readFileSync(path.join(root, "assets/report.js"), "utf8");
const errors = [];
const dom = new JSDOM(html.replace('<script src="data/demo_fixtures.js"></script>', "").replace('<script src="assets/report.js"></script>', ""), { runScripts: "outside-only", url: "http://localhost:8011/report.html?org=case_tcs&path=open_source" });
const w = dom.window;
w.addEventListener("error", (e) => errors.push(e.message));
w.eval(fixtures);
w.eval(script);
const text = w.document.getElementById("report").textContent;
const results = [];
const check = (name, ok, detail) => results.push((ok ? "PASS " : "FAIL ") + name + (detail ? "  [" + detail + "]" : ""));
check("cover names the organisation", text.includes("Case: TCS"));
check("headcount is shown from the case data, not as missing", text.includes("580,000"));
check("grade is shown with its intensity", w.document.body.textContent.includes("Grade") && !text.includes("Not graded: no headcount"));
check("uncalculated Scope 1 is not shown as zero", text.includes("Not calculated"));
check("identity fields are left for the company, not invented", text.includes("To be provided"));
check("sections are numbered 1 to 9", ["Organisation", "Summary of results", "Emissions by scope", "Energy and other", "Emission factors", "Assumptions and estimates", "Reduction options", "Limitations", "Review and sign-off"].every((h) => text.includes(h)));
check("sign-off block is present", text.includes("Prepared by") && text.includes("Approved by"));
check("no script errors", errors.length === 0, errors.join("; "));
console.log(results.join("\n"));
const failed = results.filter((r) => r.startsWith("FAIL")).length;
console.log("\n" + (results.length - failed) + " passed, " + failed + " failed");
process.exit(failed ? 1 : 0);
